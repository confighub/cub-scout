#!/usr/bin/env python3
"""Generate, record and serve the gitops-settings-fleet eval case.

The fleet is 240 Argo CD Applications in 12 projects and 60 Flux Kustomizations
and HelmReleases in 8 namespaces, written from a fixed seed so the expected
answer is known before any tool looks at the cluster.

    go build ./cmd/cub-scout
    python3 evals/gitops-settings-fleet/record.py up      # generate, record, leave the cluster running
    # ... run the case live (see README.md) ...
    python3 evals/gitops-settings-fleet/record.py down    # delete the cluster

`up` writes scenario.yaml, expected.json, fixtures/cluster, scaffold.sh, the
graders, guard mocks and recording.json, checks that the real MCP tool gives
the expected answer, and leaves an owned kind cluster running with a private
kubeconfig. The with-cub-scout arm runs against that cluster, because a
recording cannot answer every combination of the tool's filters; the baseline
arm reads the export. The shared kubeconfig is never written.
"""
import importlib.util, json, os, pathlib, random, shutil, sys, tempfile

CASE = pathlib.Path(__file__).resolve().parent
REPO = CASE.parent.parent
STATE = CASE / ".live"  # git-ignored: the running cluster's name and kubeconfig
SEED = 839
PROJECTS = ["payments", "platform", "data", "identity", "search", "media", "billing", "growth", "logistics", "risk", "mobile", "internal"]
SERVICES = ["api", "web", "worker", "gateway", "cron", "cache", "proxy", "events", "reports", "admin", "auth", "notify", "export",
            "import", "sync", "scheduler", "metrics", "router", "indexer", "batch"]
# (label, weight, automated block or None, counts as "syncs automatically without self-heal")
POLICIES = [
    ("full", 68, {"prune": True, "selfHeal": True}, False),
    ("heal-no-prune", 8, {"selfHeal": True}, False),
    ("no-heal-absent", 4, {"prune": True}, True),
    ("no-heal-false", 3, {"prune": True, "selfHeal": False}, True),
    ("auto-empty", 2, {}, True),
    ("manual", 9, None, False),
    ("disabled", 3, {"enabled": False, "prune": True, "selfHeal": False}, False),
    ("manual-options", 3, "options-only", False),
]
OPTIONS = ["ServerSideApply=true", "CreateNamespace=true", "PruneLast=true", "Validate=false", "ApplyOutOfSyncOnly=true"]
FLUX_NAMESPACES = ["flux-system", "team-a", "team-b", "team-c", "team-d", "team-e", "team-f", "team-g"]
KUSTOMIZATIONS = ["infrastructure", "apps", "monitoring", "tenants", "secrets"]
RELEASES = ["redis", "postgres", "grafana", "loki", "kafka", "vault"]

GUARD = """---
type: fixed
error: true
---

This case runs against a live cluster, not recordings. Run it with --mocks off
and PATH from evals/scripts/live-path.sh; see this case's README.md.
"""


def shared():
    spec = importlib.util.spec_from_file_location("settings_record", CASE.parent / "gitops-settings-no-self-heal" / "record.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def yaml_value(value):
    return "true" if value is True else "false" if value is False else str(value)


def generate():
    rng = random.Random(SEED)
    out = ["# Generated by record.py from seed %d. Deployer objects only: no controller is installed." % SEED]
    for namespace in ["argocd"] + FLUX_NAMESPACES:
        out += ["---", "apiVersion: v1", "kind: Namespace", "metadata:", "  name: " + namespace]
    out += ["---", "apiVersion: v1", "kind: ConfigMap", "metadata:", "  name: argocd-cm", "  namespace: argocd",
            "  labels:", "    app.kubernetes.io/part-of: argocd", "data:", "  url: https://argocd.example.test"]
    for project in PROJECTS:
        out += ["---", "apiVersion: argoproj.io/v1alpha1", "kind: AppProject", "metadata:", "  name: " + project, "  namespace: argocd",
                "spec:", "  sourceRepos:", "  - '*'", "  destinations:", "  - namespace: '*'", "    server: '*'"]
    no_self_heal, suspended, mix = [], [], {}
    weights = [p[1] for p in POLICIES]
    for project in PROJECTS:
        for service in SERVICES:
            name = project + "-" + service
            label, _, automated, counts = rng.choices(POLICIES, weights=weights)[0]
            mix[label] = mix.get(label, 0) + 1
            if counts:
                no_self_heal.append("argocd/" + name)
            out += ["---", "apiVersion: argoproj.io/v1alpha1", "kind: Application", "metadata:", "  name: " + name, "  namespace: argocd",
                    "spec:", "  project: " + project, "  source:", "    repoURL: https://git.example.test/%s/%s.git" % (project, service),
                    "    path: deploy", "    targetRevision: main", "  destination:", "    server: https://kubernetes.default.svc",
                    "    namespace: " + name]
            options = rng.sample(OPTIONS, rng.choice([0, 0, 1, 1, 2]))
            if automated is None and not options:
                continue
            if automated == "options-only":
                automated, options = None, options or ["CreateNamespace=true"]
            out.append("  syncPolicy:")
            if automated is not None:
                if automated:
                    out.append("    automated:")
                    out += ["      %s: %s" % (key, yaml_value(value)) for key, value in automated.items()]
                else:
                    out.append("    automated: {}")
            if options:
                out.append("    syncOptions:")
                out += ["    - " + option for option in options]
    out += ["---", "apiVersion: source.toolkit.fluxcd.io/v1", "kind: GitRepository", "metadata:", "  name: fleet", "  namespace: flux-system",
            "spec:", "  interval: 10m", "  url: https://git.example.test/platform/fleet.git", "  ref:", "    branch: main"]
    for namespace in FLUX_NAMESPACES:
        for name in KUSTOMIZATIONS:
            state = rng.choices(["absent", "false", "true"], weights=[70, 15, 15])[0]
            out += ["---", "apiVersion: kustomize.toolkit.fluxcd.io/v1", "kind: Kustomization", "metadata:", "  name: " + name,
                    "  namespace: " + namespace, "spec:", "  interval: 10m", "  path: ./%s/%s" % (namespace, name),
                    "  prune: " + yaml_value(rng.random() < 0.8), "  sourceRef:", "    kind: GitRepository", "    name: fleet",
                    "    namespace: flux-system"]
            if state != "absent":
                out.append("  suspend: " + state)
            if state == "true":
                suspended.append("Kustomization/%s/%s" % (namespace, name))
    release_namespaces = FLUX_NAMESPACES[1:]
    for namespace in release_namespaces:
        out += ["---", "apiVersion: source.toolkit.fluxcd.io/v1", "kind: HelmRepository", "metadata:", "  name: charts",
                "  namespace: " + namespace, "spec:", "  interval: 10m", "  url: https://charts.example.test"]
    placed = 0
    for namespace in release_namespaces:
        for name in rng.sample(RELEASES, 3 if placed < 18 else 2):
            placed += 1
            state = rng.choices(["absent", "false", "true"], weights=[70, 15, 15])[0]
            out += ["---", "apiVersion: helm.toolkit.fluxcd.io/v2", "kind: HelmRelease", "metadata:", "  name: " + name,
                    "  namespace: " + namespace, "spec:", "  interval: 10m", "  chart:", "    spec:", "      chart: " + name,
                    "      version: 1.0.0", "      sourceRef:", "        kind: HelmRepository", "        name: charts"]
            if state != "absent":
                out.append("  suspend: " + state)
            if rng.random() < 0.3:
                out += ["  driftDetection:", "    mode: " + rng.choice(["enabled", "warn"])]
            if state == "true":
                suspended.append("HelmRelease/%s/%s" % (namespace, name))
    expected = {"seed": SEED, "applications": len(PROJECTS) * len(SERVICES), "kustomizations": len(FLUX_NAMESPACES) * len(KUSTOMIZATIONS),
                "helmreleases": placed, "applicationPolicyMix": dict(sorted(mix.items())),
                "noSelfHeal": sorted(no_self_heal), "suspended": sorted(suspended)}
    (CASE / "scenario.yaml").write_text("\n".join(out) + "\n")
    (CASE / "expected.json").write_text(json.dumps(expected, indent=2) + "\n")
    return expected


def write_case(expected):
    lib = shared()
    lib.write_graders(CASE, {"NO_SELF_HEAL": expected["noSelfHeal"], "SUSPENDED": expected["suspended"]})
    mocks = CASE / "mocks" / "cub-scout"
    shutil.rmtree(CASE / "mocks", ignore_errors=True)
    mocks.mkdir(parents=True)
    for tool in ["doctor", "explain", "gitops_settings", "gitops_status", "map", "release_check", "scan", "trace"]:
        (mocks / (tool + ".md")).write_text(GUARD)
    # The live-only variant has no export; it shares these graders and guards.
    live = CASE.parent / "gitops-settings-fleet-live"
    for name in ["graders", "mocks"]:
        shutil.rmtree(live / name, ignore_errors=True)
        shutil.copytree(CASE / name, live / name)


def up():
    lib = shared()
    binary = REPO / "cub-scout"
    assert binary.exists(), "build first: go build ./cmd/cub-scout"
    assert not STATE.exists(), "a cluster from an earlier `up` is recorded in %s; run `down` first" % STATE
    expected = generate()
    work = pathlib.Path(tempfile.mkdtemp(prefix="scout-eval-fleet-"))
    work.chmod(0o700)
    home = pathlib.Path.home() / ".kube/config"
    before = lib.sha(home) if home.exists() else None
    name, cfg, env = lib.provision(work)
    try:
        lib.run(["kubectl", "apply", "--server-side", "-f", str(CASE / "scenario.yaml")], env=env, timeout=900)
        cluster = lib.export_cluster(env, CASE)
        lib.write_scaffold(CASE)
        write_case(expected)
        # The recorded answer is checked against the generator's own table,
        # which was written before the cluster existed.
        replies = lib.mcp_session(str(binary), lib.standalone_env(env, work), [
            ("tools/call", {"name": "gitops_settings", "arguments": {"setting": ["self-heal=off"], "view": "deployers"}}),
            ("tools/call", {"name": "gitops_settings", "arguments": {"setting": ["suspend=on"], "view": "deployers"}}),
            ("tools/call", {"name": "gitops_settings", "arguments": {}}),
        ])
        heal = json.loads(lib.text_of(replies[0]))
        suspend = json.loads(lib.text_of(replies[1]))
        got_heal = sorted(d["namespace"] + "/" + d["name"] for d in heal["deployers"])
        got_suspend = sorted("%s/%s/%s" % (d["kind"], d["namespace"], d["name"]) for d in suspend["deployers"])
        assert got_heal == expected["noSelfHeal"], ("tool disagrees on self-heal", sorted(set(got_heal) ^ set(expected["noSelfHeal"])))
        assert got_suspend == expected["suspended"], ("tool disagrees on suspend", sorted(set(got_suspend) ^ set(expected["suspended"])))
        assert heal["complete"] and suspend["complete"]
        sizes = {"export": sum(p.stat().st_size for p in cluster.glob("*.yaml")),
                 "gitopsSettingsDefault": len(lib.text_of(replies[2])),
                 "gitopsSettingsSelfHealOffDeployers": len(lib.text_of(replies[0])),
                 "gitopsSettingsSuspendOnDeployers": len(lib.text_of(replies[1]))}
        lib.write_manifest(CASE, binary, [
            "Generated from seed %d; expected.json was written by the generator before the cluster existed." % SEED,
            "Deployer objects only. No GitOps controller is installed: nothing reconciles and no object has a status.",
            "The with-cub-scout arm runs live against the recording cluster; the mocks are guards that fail without --mocks off.",
            "The real MCP tool's answers for self-heal=off and suspend=on equal expected.json (asserted at recording time).",
        ], {"bytes": sizes})
        STATE.write_text(json.dumps({"name": name, "kubeconfig": str(cfg), "context": "kind-" + name, "work": str(work)}) + "\n")
        assert (lib.sha(home) if home.exists() else None) == before, "shared kubeconfig changed"
        print(json.dumps({"context": "kind-" + name, "kubeconfig": str(cfg), "expected": {k: len(v) for k, v in expected.items() if isinstance(v, list)}, "bytes": sizes}))
    except BaseException:
        lib.delete_cluster(name, cfg)
        shutil.rmtree(work, ignore_errors=True)
        raise


def down():
    lib = shared()
    state = json.loads(STATE.read_text())
    lib.delete_cluster(state["name"], state["kubeconfig"])
    shutil.rmtree(state["work"], ignore_errors=True)
    STATE.unlink()
    print("deleted " + state["name"])


if __name__ == "__main__":
    {"up": up, "down": down, "generate": lambda: print(json.dumps({k: (len(v) if isinstance(v, list) else v) for k, v in generate().items()}))}[sys.argv[1] if len(sys.argv) > 1 else ""]()
