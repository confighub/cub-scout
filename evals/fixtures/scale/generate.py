#!/usr/bin/env python3
"""Generate evals/fixtures/scale/scenario.yaml: 300 Deployments in 30 namespaces.

Deterministic (seeded), so the scenario, its recording and the expected
answers in evals/scale/*/prompt.md stay in step. Owners are given by labels
and applied under each owner's field manager by evals/fixtures/setup.sh:
Flux 120, Argo CD 90, Helm 45, ConfigHub 33, unmanaged 12. Two Deployments
run an image that does not exist; every other one is scaled to zero, which
keeps a single kind node under its pod limit while the objects stay in the
export.

Usage: evals/fixtures/scale/generate.py   (prints the expected answers)
"""
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
NAMESPACES = ["team-%02d" % i for i in range(1, 31)]
APPS = ["api", "web", "worker", "cron", "gateway", "auth", "search", "cache", "billing", "notify"]
COUNTS = {"flux": 120, "argocd": 90, "helm": 45, "confighub": 33, "none": 12}
FAILING = 2


def plan():
    rng = random.Random(603)
    owners = [o for o, n in COUNTS.items() for _ in range(n)]
    rng.shuffle(owners)
    workloads = [(ns, app, owners[i * len(APPS) + j]) for i, ns in enumerate(NAMESPACES) for j, app in enumerate(APPS)]
    managed = [k for k, w in enumerate(workloads) if w[2] in ("flux", "argocd")]
    failing = set(rng.sample(managed, FAILING))
    return workloads, failing


def labels_for(ns, app, owner):
    labels = {"app": app}
    annotations = {}
    if owner == "flux":
        labels.update({"kustomize.toolkit.fluxcd.io/name": ns + "-apps", "kustomize.toolkit.fluxcd.io/namespace": "flux-system"})
    elif owner == "argocd":
        annotations["argocd.argoproj.io/tracking-id"] = "%s:apps/Deployment:%s/%s" % (ns, ns, app)
        labels["argocd.argoproj.io/instance"] = ns
    elif owner == "helm":
        labels.update({"app.kubernetes.io/managed-by": "Helm", "app.kubernetes.io/instance": app, "helm.sh/chart": "%s-1.0.0" % app})
        annotations.update({"meta.helm.sh/release-name": app, "meta.helm.sh/release-namespace": ns})
    elif owner == "confighub":
        labels["confighub.com/UnitSlug"] = "%s-%s" % (ns, app)
    return labels, annotations


def yaml_map(d, indent):
    pad = " " * indent
    return "".join('%s%s: "%s"\n' % (pad, k, v) for k, v in sorted(d.items()))


def main():
    workloads, failing = plan()
    docs = []
    for ns in NAMESPACES:
        docs.append("apiVersion: v1\nkind: Namespace\nmetadata:\n  name: %s\n" % ns)
    # The controllers' namespaces, as in a cluster that runs Flux and Argo CD.
    for ns in ("flux-system", "argocd"):
        docs.append("apiVersion: v1\nkind: Namespace\nmetadata:\n  name: %s\n" % ns)
    for k, (ns, app, owner) in enumerate(workloads):
        labels, annotations = labels_for(ns, app, owner)
        broken = k in failing
        image = "registry.k8s.io/pause:0.0.0-%s-%s" % (ns, app) if broken else "registry.k8s.io/pause:3.9"
        doc = "apiVersion: apps/v1\nkind: Deployment\nmetadata:\n  name: %s\n  namespace: %s\n  labels:\n%s" % (app, ns, yaml_map(labels, 4))
        if annotations:
            doc += "  annotations:\n" + yaml_map(annotations, 4)
        doc += ("spec:\n  replicas: %d\n  selector:\n    matchLabels:\n      app: %s\n  template:\n    metadata:\n"
                "      labels:\n        app: %s\n    spec:\n      containers:\n        - name: %s\n          image: %s\n"
                % (1 if broken else 0, app, app, app, image))
        docs.append(doc)
    header = "# Generated by evals/fixtures/scale/generate.py. Do not edit.\n"
    open(os.path.join(HERE, "scenario.yaml"), "w").write(header + "---\n".join(docs))

    counts = {o: sum(1 for w in workloads if w[2] == o) for o in COUNTS}
    print("COUNTS: flux=%(flux)d argocd=%(argocd)d helm=%(helm)d confighub=%(confighub)d unmanaged=%(none)d" % counts)
    print("UNMANAGED: " + ", ".join("%s/%s" % (ns, app) for ns, app, o in workloads if o == "none"))
    print("FAILING: " + ", ".join("%s/%s" % (workloads[k][0], workloads[k][1]) for k in sorted(failing)))


if __name__ == "__main__":
    main()
